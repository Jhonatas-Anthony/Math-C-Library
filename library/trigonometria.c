#include "trigonometria.h"

float asine(float oppositeSide, float hipotenuse) {
	return oppositeSide / hipotenuse;
}

float acosine(float adjacentSide, float hipotenuse) {
	return adjacentSide / hipotenuse;
}

float atangent(float oppositeSide, float adjacentSide) {
	return oppositeSide / adjacentSide;
}
